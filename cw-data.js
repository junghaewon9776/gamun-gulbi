// 묶음 → [낱말, 뜻풀이] 목록
function cwPool(id){
  if(id === "kn" && typeof NAT !== "undefined"){
    var out = [];
    NAT.forEach(function(x){ var nm = x[1], cp = x[2];
      if(/^[가-힣]{2,5}$/.test(nm)) out.push([nm, "수도가 「" + cp + "」인 나라 (" + x[3] + ")"]);
      if(/^[가-힣]{2,5}$/.test(cp) && cp !== nm) out.push([cp, "「" + nm + "」의 수도"]); });
    return out;
  }
  if(id === "km") return cwPool("kw").concat(cwPool("kn"));
  var g = id.length > 1 && id !== "kw" ? id.slice(1) : "";
  return CW_WORDS.filter(function(w){ return !g || w[2] === g || (g === "놀" && w[2] === "놀"); }).map(function(w){ return [w[0], w[1]]; });
}
